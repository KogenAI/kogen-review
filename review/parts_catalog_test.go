func TestGeneratedMarker(t *testing.T) {
	body := strings.Repeat("row\n", 2000)
	marker := "# Code generated by sh gen/table.sh; DO NOT EDIT.\n"
	for _, tc := range []struct {
		name, content string
		command       string
		line          int
	}{
		{"line 1", marker + body, "sh gen/table.sh", 1},
		{"line 5", strings.Repeat("x\n", 4) + marker + body, "sh gen/table.sh", 5},
		{"line 6", strings.Repeat("x\n", 5) + marker + body, "", 0},
		{"a dot", "// Code generated by go run gen.go. DO NOT EDIT.\n" + body, "go run gen.go", 1},
		{"no separator", "// Code generated by go run gen.go DO NOT EDIT.\n" + body, "go run gen.go", 1},
		{"the first match counts", marker + "# Code generated by other; DO NOT EDIT.\n" + body, "sh gen/table.sh", 1},
		{"an empty command", "# Code generated by  ; DO NOT EDIT.\n# Code generated by x; DO NOT EDIT.\n" + body, "", 0},
		{"6001 bytes", marker + strings.Repeat("a", MaterialPartBytes-len(marker)) + "\n", "sh gen/table.sh", 1},
		{"6000 bytes", marker + strings.Repeat("a", MaterialPartBytes-len(marker)-1) + "\n", "", 0},
		{"a NUL", marker + body + "\x00", "", 0},
		{"invalid UTF-8", marker + body + "\xff", "", 0},
	} {
		command, line, ok := generatedMarkerOf(tc.content)
		if tc.command == "" && ok || tc.command != "" && (!ok || command != tc.command || line != tc.line) {
			t.Errorf("%s: got %q, line %d, %v; want %q, line %d", tc.name, command, line, ok, tc.command, tc.line)
		}
	}
	if len(marker+strings.Repeat("a", MaterialPartBytes-len(marker))+"\n") != MaterialPartBytes+1 {
		t.Fatal("the 6001-byte case is not 6001 bytes")
	}
}

