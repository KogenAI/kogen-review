// wideExec starts sessions that record their brief and approve; the session numbered foreign
// (1-based, 0: none) answers under another session's handle.
type wideExec struct {
	briefs  []executor.Brief
	foreign int
	size    func(executor.Brief) int // when set, the executor reports this first-prompt size
}

// sizedWide is a wideExec that reports its first prompt size through executor.PromptSizer.
type sizedWide struct{ *wideExec }

func (s sizedWide) FirstPromptBytes(_ string, brief executor.Brief) int { return s.size(brief) }

func wideDescriptor() executor.Descriptor {
	return executor.Descriptor{Name: "fixture-executor", Contract: "1", Version: "1.0.0",
		RoleCapabilities: map[string]executor.RoleCapabilities{executor.RoleReview: {}}}
}

func (x *wideExec) Describe() executor.Descriptor { return wideDescriptor() }
func (x *wideExec) Start(_ context.Context, task executor.Task, _ executor.Sink) (executor.Session, error) {
	x.briefs = append(x.briefs, task.Brief)
	return &wideSession{id: fmt.Sprintf("review-session-%d", len(x.briefs)), foreign: len(x.briefs) == x.foreign}, nil
}

type wideSession struct {
	id      string
	foreign bool
}

func (s *wideSession) Handle() executor.Handle {
	return executor.Handle{Role: executor.RoleReview, Executor: "fixture-executor", Version: "1.0.0", SessionID: s.id}
}
func (s *wideSession) Close() error { return nil }
func (s *wideSession) Round(context.Context, executor.Input) (executor.RoundResult, error) {
	h := s.Handle()
	if s.foreign {
		h.SessionID += "-foreign"
	}
	return executor.RoundResult{
		Ending: executor.EndFinish, Structured: json.RawMessage(`{"verdict":"approve","findings":[]}`), Handle: h,
		Usage: executor.Usage{Input: core.Count(0), Cached: core.Count(0), Output: core.Count(0), Reasoning: core.Count(0), State: executor.UsageComplete},
	}, nil
}

// generatedRows is the data file that sh gen/table.sh writes for n rows.
func generatedRows(n int) string {
	var b strings.Builder
	b.WriteString("# Code generated by sh gen/table.sh; DO NOT EDIT.\n")
	for i := 1; i <= n; i++ {
		fmt.Fprintf(&b, "row %d,value %d\n", i, i)
	}
	return b.String()
}

const generatorScript = "n=$1\nexec > data/table.csv\nprintf '# Code generated by sh gen/table.sh; DO NOT EDIT.\\n'\ni=1\nwhile [ $i -le %d ]; do echo \"row $i,value $i\"; i=$((i+1)); done\n"

// wideReview reviews the candidate of r made on start in parts and returns the executor, the
// env, the run folder and the review's result.
func wideReview(t *testing.T, r *edgeRepo, start string) (*wideExec, *wideEnv, string, Result, error) {
	t.Helper()
	return wideReviewWith(t, r, start, &wideExec{})
}

// wideReviewWith is wideReview with the executor x.
func wideReviewWith(t *testing.T, r *edgeRepo, start string, x *wideExec) (*wideExec, *wideEnv, string, Result, error) {
	t.Helper()
	tree := r.git("rev-parse", "HEAD^{tree}")
	repo := git.New(r.root, nil)
	dir := t.TempDir()
	s := sys.New()
	e := &wideEnv{repo: repo, start: start}
	in := Input{
		Candidate: Candidate{Root: r.root, Repo: repo, Start: start, Tree: tree},
		Intent:    Intent{Slug: "test", Text: "intent", Role: project.Role{Provider: "openai-compatible", Model: "scripted", Effort: "medium"}},
		Evidence:  Evidence{Pass: verify.Pass{N: 1, Clean: true, Green: true, Tree: tree, Model: verify.ModelNone}},
		Tools: Tools{
			Native: func(enabled []string) *tools.Tools { return &tools.Tools{Root: r.root, Session: s, Enabled: enabled} },
			Record: func(tools.Call, tools.Output) map[string]any { return nil },
			Round: func(ctx context.Context, sess executor.Session, in executor.Input) (executor.RoundResult, error) {
				return sess.Round(ctx, in)
			},
		},
		Number: 1,
		Run:    Run{ID: "run", Dir: dir},
	}
	var ex executor.Executor = x
	if x.size != nil {
		ex = sizedWide{x}
	}
	res, err := NewExternal(ex, wideDescriptor(), 4).Review(context.Background(), in, e)
	return x, e, dir, res, err
}

// A command that fails keeps the text of its file; a changed generated file that its command
// regenerates identically sends a digest in place of its diff block. The review is in parts
// because of a large text file.
func TestReviewInPartsSummarisesOnlyAVerifiedGeneratedFile(t *testing.T) {
	r := newEdgeRepo(t)
	r.write("gen/table.sh", fmt.Sprintf(generatorScript, 800))
	r.write("data/table.csv", generatedRows(800))
	start := r.commit("start", nil)
	r.write("gen/table.sh", fmt.Sprintf(generatorScript, 900))
	r.write("data/table.csv", generatedRows(900))
	r.write("data/failing.csv", "# Code generated by exit 3; DO NOT EDIT.\n"+strings.Repeat("frow\n", 2000))
	r.write("big.txt", exactly(reviewCeiling+20000, "b"))
	r.commit("candidate", nil)
	// The scripts take no argument: the command regenerates with its own row count.
	r.write("gen/table.sh", strings.ReplaceAll(fmt.Sprintf(generatorScript, 900), "n=$1\n", ""))
	r.git("add", "-A")
	r.git("commit", "-q", "--amend", "-m", "candidate")
	x, _, dir, res, err := wideReview(t, r, start)
	if err != nil || res.Record.Verdict != "approve" {
		t.Fatalf("the review is %q, %v", res.Record.Verdict, err)
	}
	var sent strings.Builder
	for _, b := range x.briefs {
		sent.WriteString(b.Dynamic)
	}
	text := sent.String()
	digest := core.HashHex([]byte(generatedRows(900)))
	for _, want := range []string{
		fmt.Sprintf("diff --git a/data/table.csv b/data/table.csv (generated: %d bytes, SHA-256 %s; regenerated by `sh gen/table.sh` with identical output; diff with git in the checkout)\n", len(generatedRows(900)), digest),
		"--- data/table.csv (changed; hunks in diff)",
		"frow\n", "--- data/failing.csv (added; mode 100644)\n",
	} {
		if !strings.Contains(text, want) {
			t.Errorf("the parts do not carry %q", want)
		}
	}
	if strings.Contains(text, "+row 850,value 850") {
		t.Error("the diff of the summarised file was sent")
	}
	raw, err := os.ReadFile(filepath.Join(dir, "executor-review", "review-1-material.json"))
	if err != nil {
		t.Fatal(err)
	}
	var ev Material
	if err := json.Unmarshal(raw, &ev); err != nil {
		t.Fatal(err)
	}
	failing := core.HashHex([]byte("# Code generated by exit 3; DO NOT EDIT.\n" + strings.Repeat("frow\n", 2000)))
	want := []GeneratedFile{{Path: "data/failing.csv", Command: "exit 3", SHA256: failing, Outcome: "kept"}, {Path: "data/table.csv", Command: "sh gen/table.sh", SHA256: digest, Outcome: "summarised"}}
	if fmt.Sprint(ev.Generated) != fmt.Sprint(want) {
		t.Errorf("the evidence records %v, want %v", ev.Generated, want)
	}
	source, err := os.ReadFile(filepath.Join(dir, "executor-review", "review-1-source.txt"))
	if err != nil || strings.Contains(string(source), "+row 850,value 850") || !strings.Contains(string(source), "frow\n") {
		t.Errorf("the retained source is not the source as cut: %v", err)
	}
}

// A regenerated file that differs, or that the command did not write, ends the review with a
// blocking finding before any session or any file is written.
func TestReviewInPartsBlocksOnAGeneratedFileThatDiffers(t *testing.T) {
	r := newEdgeRepo(t)
	r.write("gen/table.sh", strings.ReplaceAll(fmt.Sprintf(generatorScript, 800), "n=$1\n", ""))
	r.write("data/table.csv", generatedRows(800))
	start := r.commit("start", nil)
	r.write("data/table.csv", strings.Replace(generatedRows(800), "row 5,value 5", "row 5,value 6", 1))
	r.write("data/other.csv", "# Code generated by rm data/other.csv; DO NOT EDIT.\n"+strings.Repeat("orow\n", 2000))
	r.write("big.txt", exactly(reviewCeiling+20000, "b"))
	r.commit("candidate", nil)
	x, e, dir, res, err := wideReview(t, r, start)
	if se, ok := sys.AsError(err); !ok || se.Class != "candidate" || se.Reason != "review_blocked" {
		t.Fatalf("the review ended with %v", err)
	}
	if len(x.briefs) != 0 {
		t.Errorf("%d sessions were started", len(x.briefs))
	}
	if _, err := os.Stat(filepath.Join(dir, "executor-review")); !os.IsNotExist(err) {
		t.Errorf("review material was written: %v", err)
	}
	rows := strings.Replace(generatedRows(800), "row 5,value 5", "row 5,value 6", 1)
	other := "# Code generated by rm data/other.csv; DO NOT EDIT.\n" + strings.Repeat("orow\n", 2000)
	want := []map[string]any{
		{"path": "data/other.csv", "line": 1, "severity": "blocking", "message": fmt.Sprintf("generated file data/other.csv does not match the output of its regenerating command `rm data/other.csv`: reviewed SHA-256 %s, regenerated SHA-256 none (the command did not write it)", core.HashHex([]byte(other)))},
		{"path": "data/table.csv", "line": 1, "severity": "blocking", "message": fmt.Sprintf("generated file data/table.csv does not match the output of its regenerating command `sh gen/table.sh`: reviewed SHA-256 %s, regenerated SHA-256 %s", core.HashHex([]byte(rows)), core.HashHex([]byte(generatedRows(800))))},
	}
	if res.Record.Verdict != "changes" || fmt.Sprint(res.Record.Findings) != fmt.Sprint(want) {
		t.Errorf("the verdict is %q with findings %v, want %v", res.Record.Verdict, res.Record.Findings, want)
	}
	if len(e.reviewed) != 1 || e.reviewed[0].Verdict != "changes" {
		t.Errorf("the caller recorded %v", e.reviewed)
	}
}

// Only an added or changed text file that is not a rename or copy is a large generated file:
// renamed, deleted and binary paths are not considered.
func TestGeneratedCandidatesSkipRenamedDeletedAndBinaryPaths(t *testing.T) {
	r := newEdgeRepo(t)
	rows := func(tag string) string {
		return "# Code generated by sh gen/table.sh; DO NOT EDIT.\n" + strings.Repeat(tag+" row\n", 2000)
	}
	r.write("data/old.csv", rows("old"))
	r.write("data/gone.csv", rows("gone"))
	start := r.commit("start", nil)
	r.git("mv", "data/old.csv", "data/new.csv")
	r.remove("data/gone.csv")
	r.write("data/bin.csv", rows("bin")+"\x00")
	r.write("data/ok.csv", rows("ok"))
	r.commit("candidate", nil)
	c, tree, m := r.material(start)
	for path, status := range map[string]string{"data/new.csv": "changed", "data/gone.csv": "deleted", "data/bin.csv": "added", "data/ok.csv": "added"} {
		if _, e := entryOf(t, m.Files, path); e["status"] != status || (path == "data/new.csv") != (e["origin"] != "") {
			t.Fatalf("the catalog entry of %s is %v", path, e)
		}
	}
	got, err := generatedCandidates(Input{Candidate: c}, tree, m)
	if err != nil {
		t.Fatal(err)
	}
	var paths []string
	for _, f := range got {
		paths = append(paths, f.Path)
	}
	if fmt.Sprint(paths) != "[data/ok.csv]" {
		t.Errorf("the large generated files are %v, want [data/ok.csv] (catalog %v)", paths, m.Files)
	}
}

