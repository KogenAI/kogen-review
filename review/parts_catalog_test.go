// carryLayout is a source of two diff blocks and three entries, with their catalog.
func carryLayout() (partsLayout, []map[string]any) {
	layout := partsLayout{
		head:    "HEAD\n\n",
		blocks:  []diffBlock{{file: 0, text: "diff --git a/a b/a\n+aaaa\n"}, {file: 1, text: "diff --git a/b b/b\n+bbbb\n"}},
		mid:     "\nADDED\n\n",
		entries: []string{"--- a (changed; hunks in diff)", "--- b (changed; hunks in diff)", "--- c (added; mode 100644)\ncccc\n"},
	}
	files := []map[string]any{{"path": "a"}, {"path": "b"}, {"path": "c"}}
	return layout, files
}

func carryIntro(total, k int) string {
	return fmt.Sprintf("This review changes %d paths. The complete catalog of every changed path (path, status, origin, rename, mode, Git object, bytes and SHA-256) is retained in /run/review-1-material.json under \"parts\"; read an entry there when this part does not carry it. The catalog entries of the %d paths whose material this part's source carries:\n", total, k)
}

func TestCatalogCarryListsThePathsWhoseMaterialOverlapsTheSlice(t *testing.T) {
	layout, files := carryLayout()
	source := layout.source()
	c, err := newCatalogCarry("/run/review-1-material.json", files, layout)
	if err != nil {
		t.Fatal(err)
	}
	at := func(s string) int { return strings.Index(source, s) }
	blockB, entryA, entryB, entryC := at("diff --git a/b"), at("--- a "), at("--- b "), at("--- c ")
	for _, tc := range []struct {
		name     string
		from, to int
		want     string
		count    int
	}{
		{"an empty slice carries none", 0, 0, `[]`, 0},
		{"the header carries none", 0, len(layout.head), `[]`, 0},
		{"the first diff block", len(layout.head), blockB, `[{"path":"a"}]`, 1},
		{"a slice that ends one byte into the next block", len(layout.head), blockB + 1, `[{"path":"a"},{"path":"b"}]`, 2},
		{"a block that straddles the cut is in both parts", blockB + 3, entryA + 1, `[{"path":"a"},{"path":"b"}]`, 2},
		{"the next part carries it too", blockB + 3, entryA, `[{"path":"b"}]`, 1},
		{"an entry and the entry that starts in it, in catalog order", entryA, entryB + 1, `[{"path":"a"},{"path":"b"}]`, 2},
		{"the last entry to the end of the source", entryC, len(source), `[{"path":"c"}]`, 1},
		{"a block and an entry of one path are listed once", len(layout.head), entryA + 1, `[{"path":"a"},{"path":"b"}]`, 2},
	} {
		if got, want := c.section(tc.from, tc.to), carryIntro(3, tc.count)+tc.want; got != want {
			t.Errorf("%s: section [%d, %d) is\n%s\nwant\n%s", tc.name, tc.from, tc.to, got, want)
		}
	}
	// A slice that grows only grows its section.
	last := ""
	for to := 0; to <= len(source); to++ {
		if s := c.section(0, to); len(s) < len(last) {
			t.Fatalf("the section of [0, %d) is shorter than the one before it", to)
		} else {
			last = s
		}
	}
}

// The catalog is carried whole at 6000 bytes and per part from 6001.
func TestCatalogCarryStartsAboveMaterialPartBytes(t *testing.T) {
	layout, _ := carryLayout()
	for _, tc := range []struct {
		extra int
		carry bool
	}{{0, false}, {1, true}} {
		files := []map[string]any{{"path": "a", "pad": ""}}
		whole, _ := json.Marshal(files)
		files[0]["pad"] = strings.Repeat("x", MaterialPartBytes-len(whole)+tc.extra)
		catalog, _ := json.Marshal(files)
		if len(catalog) != MaterialPartBytes+tc.extra {
			t.Fatalf("catalog is %d bytes", len(catalog))
		}
		got, err := carryFor(catalog, "dir", 1, MaterialSet{Files: files, layout: layout})
		if err != nil {
			t.Fatal(err)
		}
		if (got != nil) != tc.carry {
			t.Errorf("a %d-byte catalog is carried per part: %v, want %v", len(catalog), got != nil, tc.carry)
		}
		if got != nil && !filepath.IsAbs(got.file) {
			t.Errorf("the retained catalog file %q is not absolute", got.file)
		}
	}
}

