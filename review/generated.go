// A large generated data file is checked against the command that regenerates it before anything
// of a review in parts is sent. Identical output sends a digest instead of the text; different
// output is a blocking finding. A command that cannot regenerate it leaves the text as it is.

// GeneratedFile is the evidence of one large generated file of a review in parts: its path, the
// command that regenerates it, the SHA-256 of its content in the reviewed tree and whether its
// text was left out of the review source (outcome "summarised") or kept in it ("kept").
type GeneratedFile struct {
	Path    string `json:"path"`
	Command string `json:"command"`
	SHA256  string `json:"sha256"`
	Outcome string `json:"outcome"`
}

const (
	generatedSummarised = "summarised"
	generatedKept       = "kept"
)

// generatedMarker is the line that marks a file as generated; its first group is the command.
var generatedMarker = regexp.MustCompile(`Code generated by (.+?)[.;]? DO NOT EDIT\.`)

// generatedMarkerLines is how many lines from the top of a file may carry the marker.
const generatedMarkerLines = 5

// regenerateLimit is how long a regenerating command may run.
var regenerateLimit = 2 * time.Minute

// generatedCandidate is a large generated file of the reviewed tree.
type generatedCandidate struct {
	GeneratedFile
	index   int    // in the catalog
	line    int    // the marker line, 1-based
	content string // in the reviewed tree
	mode    string
	// regenerated is the SHA-256 of what the command wrote, or "" when it did not write the file;
	// mismatch and kept are the outcomes of the regeneration.
	regenerated string
	mismatch    bool
}

// generatedMarkerOf is the regenerating command and the 1-based marker line of content, which
// must be a large generated file's content: longer than MaterialPartBytes, valid UTF-8 without
// NUL, with the marker in its first generatedMarkerLines lines.
func generatedMarkerOf(content string) (command string, line int, ok bool) {
	if len(content) <= MaterialPartBytes || !utf8.ValidString(content) || strings.Contains(content, "\x00") {
		return "", 0, false
	}
	lines := strings.SplitN(content, "\n", generatedMarkerLines+1)
	for i, l := range lines[:min(len(lines), generatedMarkerLines)] {
		if m := generatedMarker.FindStringSubmatch(l); m != nil {
			command = strings.TrimSpace(m[1])
			return command, i + 1, command != ""
		}
	}
	return "", 0, false
}

// generatedCandidates are the large generated files of the review material m, in path order.
func generatedCandidates(in Input, tree string, m MaterialSet) ([]*generatedCandidate, error) {
	var out []*generatedCandidate
	for i, f := range m.Files {
		path, _ := f["path"].(string)
		status, _ := f["status"].(string)
		origin, _ := f["origin"].(string)
		size, _ := f["bytes"].(int)
		if (status != "added" && status != "changed") || origin != "" || f["mode"] == "160000" || size <= MaterialPartBytes {
			continue
		}
		content, err := in.Candidate.Repo.OK("show", tree+":"+path)
		if err != nil {
			return nil, err
		}
		command, line, ok := generatedMarkerOf(content)
		if !ok {
			continue
		}
		mode, _ := f["mode"].(string)
		out = append(out, &generatedCandidate{
			GeneratedFile: GeneratedFile{Path: path, Command: command, SHA256: core.HashHex([]byte(content))},
			index:         i, line: line, content: content, mode: mode,
		})
	}
	slices.SortFunc(out, func(a, b *generatedCandidate) int { return strings.Compare(a.Path, b.Path) })
	return out, nil
}

// regenerate runs every distinct regenerating command once, each in its own scratch copy of the
// reviewed tree, and sets each file's outcome: summarised (identical output), mismatch (different
// output, or the file not written) or kept (the command failed, timed out or did not start).
func regenerate(ctx context.Context, in Input, tree string, files []*generatedCandidate) error {
	var commands []string
	for _, f := range files {
		if !slices.Contains(commands, f.Command) {
			commands = append(commands, f.Command)
		}
	}
	for _, command := range commands {
		dir, err := os.MkdirTemp("", "kogen-regenerate-")
		if err != nil {
			return err
		}
		err = func() error {
			defer os.RemoveAll(dir)
			archive, err := in.Candidate.Repo.OK("archive", "--format=tar", tree)
			if err != nil {
				return err
			}
			if err := extractTree(dir, archive); err != nil {
				return err
			}
			ran := runRegenerate(ctx, dir, command)
			for _, f := range files {
				if f.Command != command {
					continue
				}
				switch {
				case !ran:
					f.Outcome = generatedKept
				default:
					got, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(f.Path)))
					switch {
					case err == nil && string(got) == f.content:
						f.Outcome = generatedSummarised
					default:
						f.Outcome, f.mismatch = generatedKept, true
						if err == nil {
							f.regenerated = core.HashHex(got)
						}
					}
				}
			}
			return nil
		}()
		if err != nil {
			return err
		}
	}
	return nil
}

// runRegenerate runs command with sh in dir, with no input and this process's environment, and
// reports whether it ran and exited 0 within regenerateLimit.
func runRegenerate(ctx context.Context, dir, command string) bool {
	ctx, cancel := context.WithTimeout(ctx, regenerateLimit)
	defer cancel()
	cmd := exec.CommandContext(ctx, "sh", "-c", command)
	cmd.Dir = dir
	cmd.Env = os.Environ()
	cmd.WaitDelay = 5 * time.Second
	return cmd.Run() == nil
}

// extractTree writes the files of a tar archive of a tree into dir.
func extractTree(dir, archive string) error {
	tr := tar.NewReader(strings.NewReader(archive))
	for {
		h, err := tr.Next()
		if errors.Is(err, io.EOF) {
			return nil
		}
		if err != nil {
			return err
		}
		name := filepath.Join(dir, filepath.FromSlash(h.Name))
		if rel, err := filepath.Rel(dir, name); err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
			return fmt.Errorf("the archive of the reviewed tree names %q outside its folder", h.Name)
		}
		switch h.Typeflag {
		case tar.TypeDir:
			err = os.MkdirAll(name, 0o755)
		case tar.TypeReg:
			if err = os.MkdirAll(filepath.Dir(name), 0o755); err == nil {
				var data []byte
				if data, err = io.ReadAll(tr); err == nil {
					err = os.WriteFile(name, data, h.FileInfo().Mode().Perm())
				}
			}
		case tar.TypeSymlink:
			if err = os.MkdirAll(filepath.Dir(name), 0o755); err == nil {
				err = os.Symlink(h.Linkname, name)
			}
		}
		if err != nil {
			return err
		}
	}
}

// generatedFindings are the blocking findings of the files whose regenerated output differs, in
// path order.
func generatedFindings(files []*generatedCandidate) []map[string]any {
	var findings []map[string]any
	for _, f := range files {
		if !f.mismatch {
			continue
		}
		regenerated := f.regenerated
		if regenerated == "" {
			regenerated = "none (the command did not write it)"
		}
		findings = append(findings, map[string]any{
			"path": f.Path, "line": f.line, "severity": "blocking",
			"message": fmt.Sprintf("generated file %s does not match the output of its regenerating command `%s`: reviewed SHA-256 %s, regenerated SHA-256 %s", f.Path, f.Command, f.SHA256, regenerated),
		})
	}
	return findings
}

// generatedStop ends the review with a Kogen-made changes verdict of the findings, judged by the
// ordinary evaluation on the green pass and its tree.
func (v *xreview) generatedStop(ctx context.Context, role project.Role, findings []map[string]any) (Result, error) {
	in := v.in
	findings, dropped := cutFindings(findings)
	base := in.Evidence.Pass
	r := &run{in: in, env: v.env, pass: base, external: true, base: &base, sess: Session{Role: role, Usage: core.ZeroTokens(), Seen: base.Tree}}
	res, _, err := r.evaluate(ctx, Verdict{Verdict: "changes", Findings: findings, Dropped: dropped}, base.Tree)
	v.defects = append(v.defects, r.sess.Blockers...)
	return res, err
}

// summarised is m with the text of every summarised generated file left out of its parts source.
func (m MaterialSet) summarised(files []*generatedCandidate) MaterialSet {
	layout := m.layout
	layout.blocks = slices.Clone(layout.blocks)
	layout.entries = slices.Clone(layout.entries)
	texts := slices.Clone(m.PartsTexts)
	for _, f := range files {
		if f.Outcome != generatedSummarised {
			continue
		}
		digest := fmt.Sprintf("generated: %d bytes, SHA-256 %s; regenerated by `%s` with identical output", len(f.content), f.SHA256, f.Command)
		if m.Files[f.index]["status"] == "added" {
			layout.entries[f.index] = fmt.Sprintf("--- %s (added; mode %s; %s; full text in the checkout)", f.Path, f.mode, digest)
			texts = slices.DeleteFunc(texts, func(t MaterialFileText) bool { return t.Path == f.Path })
			continue
		}
		for i, blk := range layout.blocks {
			if blk.file == f.index {
				layout.blocks[i].text = fmt.Sprintf("diff --git a/%s b/%s (%s; diff with git in the checkout)\n", f.Path, f.Path, digest)
			}
		}
	}
	m.layout, m.PartsTexts = layout, texts
	m.PartsSource = layout.source()
	return m
}

// generatedEvidence is the evidence of the large generated files, one per file in path order.
func generatedEvidence(files []*generatedCandidate) []GeneratedFile {
	var out []GeneratedFile
	for _, f := range files {
		out = append(out, f.GeneratedFile)
	}
	return out
}
